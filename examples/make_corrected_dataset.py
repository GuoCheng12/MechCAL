"""Build the structure-corrected copy of PhotoMechBench raw_v2_119 (deterministic).

    python examples/make_corrected_dataset.py           # writes benchmarks/photomechbench/raw_v2_119_corrected/
    python examples/make_corrected_dataset.py --check   # verifies the committed copy equals a fresh build

Input: the frozen snapshot benchmarks/photomechbench/raw_v2_119 and the correction list
benchmarks/photomechbench/corrections/structure_corrections.json. Output: cases/<case_id>.json
(each with a ``structure_verification`` record; for corrected cases the SMILES is replaced and the
original kept), inputs.csv (case_id,smiles in the snapshot's order), manifest.json (what changed,
checksums of inputs and outputs) and README.md. References, labels and evidence are copied
unchanged.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mechcal.eval.dataset import CORRECTIONS, DATASET, RAW  # noqa: E402
from mechcal.eval.structure_checks import structure_warnings  # noqa: E402

README = """# raw_v2_119_corrected

Generated by `examples/make_corrected_dataset.py`; do not edit by hand. Source: the frozen
`../raw_v2_119` snapshot plus `../corrections/structure_corrections.json`.

- SMILES checked against the source papers and found wrong are replaced; the original is kept in
  each case's `structure_verification.original_smiles`.
- Every case has `structure_verification`: `corrected`, `verified_consistent` or `unverified`
  (legacy SMILES not yet checked), `runnable` (false when the structure cannot yet be prepared
  correctly in 3D), `si_checked` when supporting information was used, and `structure_warnings`
  for patterns that were systematically wrong in the original records (mechcal.eval.structure_checks).
- References, labels and evidence are unchanged.

Changed cases: {changed}.
"""


def _dump(obj) -> str:
    return json.dumps(obj, indent=1, ensure_ascii=False) + "\n"


def build() -> dict[str, str]:
    """Relative path -> file content of the corrected dataset."""
    corrections = json.loads(CORRECTIONS.read_text(encoding="utf-8"))
    fixed = {c["case_id"]: c for c in corrections["corrections"]}
    checked = {c["case_id"]: c for c in corrections["verified_consistent"]}
    date = corrections["date"]
    with (RAW / "inputs.csv").open(encoding="utf-8", newline="") as fh:
        order = [row["case_id"] for row in csv.DictReader(fh)]
    files: dict[str, str] = {}
    smiles: dict[str, str] = {}
    for case_id in order:
        case = json.loads((RAW / "cases" / f"{case_id}.json").read_text(encoding="utf-8"))
        structure = case["public_input"]["molecule"]["structure"]
        if case_id in fixed:
            c = fixed[case_id]
            if structure["value"] != c["old_smiles"]:
                raise ValueError(f"{case_id}: snapshot SMILES differs from the correction's old_smiles")
            structure["value"] = c["new_smiles"]
            verification = {"status": "corrected", "checked": date, "original_smiles": c["old_smiles"],
                            "problem": c["problem"], "old_formula": c["old_formula"], "new_formula": c["new_formula"],
                            "basis": c["basis"], "evidence": c["evidence"], "runnable": c["runnable"]}
            if c.get("si_checked") is not None:
                verification["si_checked"] = c["si_checked"]
            if not c["runnable"]:
                verification["not_runnable_reason"] = c["not_runnable_reason"]
        elif case_id in checked:
            verification = {"status": "verified_consistent", "checked": date, "evidence": checked[case_id]["evidence"],
                            "runnable": True}
            if checked[case_id].get("si_checked") is not None:
                verification["si_checked"] = checked[case_id]["si_checked"]
        else:
            verification = {"status": "unverified", "note": "legacy SMILES, not yet checked against the source paper",
                            "runnable": True}
        warnings = structure_warnings(structure["value"])
        if warnings:                                  # patterns that were systematically wrong before; for review
            verification["structure_warnings"] = warnings
        case["structure_verification"] = verification
        smiles[case_id] = structure["value"]
        files[f"cases/{case_id}.json"] = _dump(case)
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["case_id", "smiles"])
    for case_id in order:
        writer.writerow([case_id, smiles[case_id]])
    files["inputs.csv"] = buf.getvalue()
    changed = sorted(fixed)
    files["README.md"] = README.format(changed=", ".join(c[-4:] for c in changed))
    sha = lambda text: hashlib.sha256(text.encode("utf-8")).hexdigest()
    files["manifest.json"] = _dump({
        "name": "photomechbench_raw_v2_119_corrected", "source_snapshot": "raw_v2_119",
        "corrections_sha256": sha(CORRECTIONS.read_text(encoding="utf-8")),
        "cases": len(order), "changed_cases": changed,
        "not_runnable": sorted(c for c, x in fixed.items() if not x["runnable"]),
        "structure_warnings": {c: w for c in order
                               if (w := json.loads(files[f"cases/{c}.json"])["structure_verification"].get("structure_warnings"))},
        "verification_counts": {s: sum(json.loads(files[f"cases/{c}.json"])["structure_verification"]["status"] == s
                                       for c in order) for s in ("corrected", "verified_consistent", "unverified")},
        "files_sha256": {path: sha(text) for path, text in sorted(files.items())},
    })
    return files


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    if args.check:
        stale = [p for p, text in files.items() if not (DATASET / p).is_file() or (DATASET / p).read_text(encoding="utf-8") != text]
        extra = sorted(str(p.relative_to(DATASET)) for p in DATASET.rglob("*") if p.is_file()
                       and str(p.relative_to(DATASET)) not in files)
        if stale or extra:
            raise SystemExit(f"corrected dataset is stale: {stale[:5]} extra: {extra[:5]}")
        print(f"ok: {len(files)} files match")
        return
    for path, text in files.items():
        target = DATASET / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    print(json.loads(files["manifest.json"])["verification_counts"], "->", DATASET)


if __name__ == "__main__":
    main()
